#!/usr/bin/env python3
"""GeocodeBR + City2Graph + NexusDB urban-service demo.

Default mode is fully deterministic and uses synthetic coordinates.

Input modes:
- --geocode-csv: geocode demand/facility CEPs through geocodebr;
- --poi-csv: load real POIs (for example niteroi_pois.csv generated by
  download_niteroi_pois.py) and build a POI proximity graph.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import unicodedata
import time
import urllib.error
import urllib.request
import uuid
from pathlib import Path

import geopandas as gpd
import pandas as pd
from shapely.geometry import Point

import city2graph as c2g


DEFAULT_URL = os.getenv("NEXUSDB_URL", "http://127.0.0.1:7474")
DEFAULT_USER = os.getenv("NEXUSDB_USER", "admin")
DEFAULT_PASSWORD = os.getenv("NEXUSDB_PASSWORD", "")
METRIC_CRS = "EPSG:31983"  # SIRGAS 2000 / UTM 23S — Rio de Janeiro region.


class NexusClient:
    def __init__(self, url: str, user: str, password: str, database: str):
        self.url = url.rstrip("/")
        self.user = user
        self.password = password
        self.database = database

    def post(self, route: str, payload: dict, timeout: int = 180) -> dict:
        req = urllib.request.Request(
            self.url + route,
            data=json.dumps(payload).encode("utf-8"),
            headers={
                "Content-Type": "application/json",
                "X-User": self.user,
                "X-Pass": self.password,
                "X-Database": self.database,
            },
            method="POST",
        )
        try:
            with urllib.request.urlopen(req, timeout=timeout) as response:
                result = json.load(response)
        except urllib.error.HTTPError as exc:
            body = exc.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"HTTP {exc.code}: {body}") from None
        except urllib.error.URLError as exc:
            raise RuntimeError(f"NexusDB connection failed: {exc}") from None

        if result.get("errors"):
            raise RuntimeError(json.dumps(result, ensure_ascii=False))
        return result

    def cypher(self, query: str) -> dict:
        return self.post(
            "/db/data/cypher",
            {"statements": [{"query": query}]},
        )

    def bulk_nodes(self, rows: list[dict]) -> dict:
        return self.post("/db/data/node/bulk", {"rows": rows})

    def bulk_relationships(self, rows: list[dict]) -> dict:
        return self.post("/db/data/relationship/bulk", {"rows": rows})


